import React, { useEffect } from 'react';
import { useAppState } from '../../contexts/AppStateContext';
import { LockOverlay, ProgressBar } from '../common';
import { AnnotationForm } from './AnnotationForm';
import { BackgroundSettings } from './BackgroundSettings';

/**
 * Main interface for integrated annotations
 * @param {boolean} inModal - If true, adapts style for modal
 * @param {function} onClose - Callback to close the modal
 */
export const IntegratedAnnotationInterface = ({ inModal = false, onClose }) => {
  const {
    annotationState,
    setAnnotationState,
    uiLock,
    setUiLock,
    currentProject,
    addLog,
    // Use persistent annotation functions from context
    annotation,
  } = useAppState();

  const {
    matrixUploads,
    loadingMatrixUploads,
    cancelRequested,
    refreshMatrixUploads,
    loadPredictionTasks,
    uploadMatrix,
    hasCsvForMethod,
    canRunAnnotation,
    runSelectedIntegrated,
    handleCancelAll,
  } = annotation;

  const {
    selectedTask,
    allRunning,
    globalProgress,
    globalProgressMessage,
    readyToView,
    selectedMethods,
    uploadedMatrixNames,
    predictionTasks,
  } = annotationState;

  const dimmed = uiLock.lockedBy === "PRED" || uiLock.lockedBy === "OPTIM";

  // UI Lock
  useEffect(() => {
    if (allRunning) {
      setUiLock({ lockedBy: "ANNO", message: "Annotations in progress..." });
    } else if (uiLock.lockedBy === "ANNO") {
      setUiLock({ lockedBy: null, message: "" });
    }
  }, [allRunning, setUiLock, uiLock.lockedBy]);

  // Load tasks on mount
  useEffect(() => {
    if (predictionTasks.length === 0) {
      loadPredictionTasks();
    }
    if (matrixUploads.length === 0) {
      refreshMatrixUploads();
    }
  }, [loadPredictionTasks, refreshMatrixUploads, predictionTasks.length, matrixUploads.length]);

  const selectedTaskData = predictionTasks.find((t) => t.taskId === selectedTask);

  const renderCsvStatus = () => {
    if (!selectedTask) return null;
    const csvMap = selectedTaskData?.csvFiles || {};
    const order = ["1H", "13C", "COSY", "HSQC"];
    return (
      <div className="csv-status">
        {order.map((t) => {
          const f = csvMap[t];
          if (!f)
            return (
              <div key={t} className="status-item missing">
                {t}: Missing
              </div>
            );
          if (!hasCsvForMethod(t))
            return (
              <div key={t} className="status-item missing">
                {t}: Invalid
              </div>
            );
          return (
            <div key={t} className="status-item success">
              {t}: Available
            </div>
          );
        })}
      </div>
    );
  };

  const goResults = () => {
    setAnnotationState((prev) => ({ ...prev, readyToView: true }));
    // In modal mode, close the modal (results are visible in MainView)
    if (inModal && onClose) {
      onClose();
    }
  };

  // Check that a project is open (after hooks to respect React rules)
  if (!currentProject) {
    return (
      <div className="annotation-interface">
        <div className="warning-box">
          <span className="warning-icon">Warning</span>
          <div>
            <h3 className="warning-title">No project open</h3>
            <p className="warning-text">
              You must create or open a project from the home page before using annotations.
              Files will be stored in your project folder.
            </p>
            <button 
              onClick={() => window.location.href = '/'} 
              className="btn btn-primary"
            >
              Return to home
            </button>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="annotation-interface" style={{ position: "relative" }}>
      {dimmed && (
        <LockOverlay message="Prediction or optimization in progress... Annotations section is temporarily unavailable." />
      )}

      <div className="header">
        <h1>Integrated Annotations (from predictions)</h1>
        <p>Annotate your spectra using CSVs generated by ML predictions</p>
      </div>

      {/* Task selection */}
      <div className="card">
        <h3>Source Prediction Task</h3>
        <div className="form-row">
          <label className="form-label">Prediction Task</label>
          <select
            className="form-input"
            value={selectedTask || ""}
            onChange={(e) =>
              setAnnotationState((prev) => ({
                ...prev,
                selectedTask: e.target.value,
                readyToView: false,
              }))
            }
            disabled={allRunning}
          >
            <option value="">Select a task...</option>
            {predictionTasks.map((task) => (
              <option key={task.taskId} value={task.taskId}>
                {task.taskId} - {new Date(task.createdAt).toLocaleString()}
                {task.canRunAnnotations ? " OK" : " !"}
              </option>
            ))}
          </select>
          <button
            className="btn btn-secondary"
            onClick={loadPredictionTasks}
            disabled={allRunning}
          >
            Refresh
          </button>
        </div>

        {selectedTask && (
          <div className="task-details">
            <h4>CSVs available in {selectedTask}:</h4>
            {renderCsvStatus()}
          </div>
        )}
      </div>

      {/* Method selection */}
      <div className="card">
        <h3>Choose methods to launch</h3>
        <div className="parameters-grid">
          {["1H", "13C", "COSY", "HSQC"].map((t) => {
            const hasCsv = hasCsvForMethod(t);
            const hasMatrix = !!uploadedMatrixNames[t];
            const checked = selectedMethods.includes(t);
            let status = "";
            if (!hasCsv) status = " (CSV missing)";
            else if (!hasMatrix) status = " (matrix missing)";
            else status = " OK";
            return (
              <label
                key={t}
                className="parameter-input"
                style={{ flexDirection: "row", alignItems: "center", gap: 8 }}
                title={
                  !hasCsv
                    ? "CSV invalid or missing"
                    : !hasMatrix
                    ? "Upload a matrix"
                    : "Ready"
                }
              >
                <input
                  type="checkbox"
                  checked={checked}
                  onChange={() => {
                    if (!hasCsv || allRunning) return;
                    setAnnotationState((prev) => {
                      const current = new Set(prev.selectedMethods);
                      let nextActive = prev.activeType;

                      if (current.has(t)) {
                        current.delete(t);
                        if (nextActive === t) {
                          const firstWithCsv = [...current].find((m) => hasCsvForMethod(m));
                          if (firstWithCsv) nextActive = firstWithCsv;
                        }
                      } else {
                        current.add(t);
                        nextActive = t;
                      }

                      return {
                        ...prev,
                        selectedMethods: Array.from(current),
                        activeType: nextActive,
                        readyToView: false,
                      };
                    });
                  }}
                  disabled={!hasCsv || allRunning}
                  style={{ width: 18, height: 18 }}
                />
                <span className="parameter-label" style={{ marginBottom: 0 }}>
                  {t}
                  {status}
                </span>
              </label>
            );
          })}
        </div>
        <div className="hint" style={{ marginTop: 8 }}>
          Select 1 to 4 methods. Backgrounds (if a <code>pdata</code> folder is
          specified) will be exported automatically on launch.
        </div>
      </div>

      <AnnotationForm
        annotationState={annotationState}
        setAnnotationState={setAnnotationState}
        allRunning={allRunning}
        hasCsvForMethod={hasCsvForMethod}
        matrixUploads={matrixUploads}
        loadingMatrixUploads={loadingMatrixUploads}
        refreshMatrixUploads={refreshMatrixUploads}
        uploadMatrix={uploadMatrix}
        addLog={addLog}
      />

      <BackgroundSettings
        annotationState={annotationState}
        setAnnotationState={setAnnotationState}
        allRunning={allRunning}
      />

      {/* Launch button */}
      <div className="action-section">
        {(() => {
          const readySelected = selectedMethods.filter((t) => canRunAnnotation(t));
          const missingMatrices = selectedMethods.filter(
            (t) => hasCsvForMethod(t) && !uploadedMatrixNames[t]
          );
          const n = readySelected.length;

          let buttonText;
          let buttonAction;
          let isDisabled;

          if (allRunning) {
            buttonText = `Annotations (${n}) in progress...`;
            buttonAction = () => {};
            isDisabled = true;
          } else if (missingMatrices.length > 0) {
            buttonText = `Missing matrices for: ${missingMatrices.join(", ")}`;
            buttonAction = () => {};
            isDisabled = true;
          } else if (n === 0) {
            buttonText = "Select at least one method";
            buttonAction = () => {};
            isDisabled = true;
          } else {
            buttonText = `Launch selected annotations (${n})`;
            buttonAction = runSelectedIntegrated;
            isDisabled = false;
          }

          return (
            <>
              <button
                onClick={buttonAction}
                disabled={isDisabled}
                className={`btn btn-primary btn-large ${!isDisabled ? "" : "disabled"}`}
              >
                {buttonText}
              </button>

              {allRunning && (
                <button
                  onClick={handleCancelAll}
                  className="btn btn-danger btn-large"
                  style={{ marginLeft: 8 }}
                  disabled={cancelRequested}
                >
                  {cancelRequested ? "Canceling..." : "Cancel"}
                </button>
              )}
            </>
          );
        })()}
      </div>

      {allRunning && (
        <div className="progress-section">
          <h4>Progress</h4>
          <ProgressBar progress={globalProgress} message={globalProgressMessage} />
        </div>
      )}

      {readyToView && !allRunning && (
        <div className="results-section" style={{ marginTop: 16 }}>
          <button className="btn btn-secondary" onClick={goResults}>
            View results
          </button>
          <div className="hint" style={{ marginTop: 8 }}>
            Results are available on the <code>/results</code> page.
          </div>
        </div>
      )}
    </div>
  );
};